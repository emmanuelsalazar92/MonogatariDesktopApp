function repairMojibake(value: string) {
  return mojibakeReplacements.reduce(
    (text, [broken, fixed]) => text.split(broken).join(fixed),
    value
  );
}

export function translateStudioText(value: string, language: Language) {
  if (!value.trim()) return value;

  const entries = [...(
    language === "es"
      ? englishToSpanishEntries
      : englishToSpanishEntries.map(([english, spanish]) => [spanish, english] as [string, string])
  )].sort((a, b) => b[0].length - a[0].length);

  const placeholders = entries.map((_, index) => `__studio_i18n_${index}__`);
  const tokenized = entries.reduce(
    (text, [source], index) => text.split(source).join(placeholders[index]),
    value
  );
  const translated = entries.reduce(
    (text, [, target], index) => text.split(placeholders[index]).join(target),
    tokenized
  );

  return repairMojibake(translated);
}

export function useLiveLocalization(language: Language) {
  React.useEffect(() => {
    document.documentElement.lang = language;
    void translateStudioText;
    void englishToSpanishEntries;
  }, [language]);
}
